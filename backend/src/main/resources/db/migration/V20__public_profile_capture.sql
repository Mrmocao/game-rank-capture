CREATE TABLE capture_public_profile_observation (
 id CHAR(36) PRIMARY KEY COMMENT '公开资料观察UUID',
 tenant_id VARCHAR(64) NOT NULL COMMENT '工作区',
 seed_observation_id BIGINT NOT NULL COMMENT '微信或抖音榜单观察ID',
 seed_rank_position INT NOT NULL COMMENT '原榜名次',
 seed_platform VARCHAR(32) NOT NULL COMMENT '原榜平台',
 seed_region VARCHAR(16) NOT NULL COMMENT '原榜地区',
 seed_name VARCHAR(500) NOT NULL COMMENT '原榜名称',
 seed_developer VARCHAR(500) NULL COMMENT '原榜开发商',
 candidate_platform VARCHAR(32) NULL COMMENT '候选详情平台',
 candidate_external_id VARCHAR(64) NULL COMMENT '候选App ID',
 candidate_name VARCHAR(500) NULL COMMENT '候选详情名称',
 candidate_developer VARCHAR(500) NULL COMMENT '候选详情开发者',
 source_key VARCHAR(64) NOT NULL COMMENT 'qimai-public',
 source_url TEXT NULL COMMENT '实际详情来源URL',
 status VARCHAR(32) NOT NULL COMMENT 'SUCCEEDED/FAILED/NO_CANDIDATE/LOGIN_REQUIRED',
 error_code VARCHAR(80) NULL COMMENT '脱敏错误码',
 captured_at DATETIME(3) NULL COMMENT '实际取得时间UTC',
 raw_sha256 CHAR(64) NULL COMMENT '原始材料摘要',
 raw_locator TEXT NULL COMMENT '相对材料路径',
 profile_json JSON NULL COMMENT '公开可见字段与口径',
 created_at DATETIME(3) NOT NULL COMMENT '写入时间UTC',
 updated_at DATETIME(3) NOT NULL COMMENT '更新时间UTC',
 UNIQUE KEY uq_public_profile_seed(tenant_id,seed_observation_id,seed_rank_position,source_key,candidate_external_id),
 KEY idx_public_profile_observation(tenant_id,seed_observation_id,status)
) COMMENT='按现有榜单名称检索的公开应用资料；不自动合并跨平台身份';
